// Shared test harness for SessionPrompt.loop tests. Tests like prompt.test.ts
// (positive-path semantics) and snapshot-tool-race.test.ts (snapshot race
// reproducer) compose the same service graph — real Session, SessionPrompt,
// ToolRegistry, Question, Permission, plus stubbed MCP and LSP. The summary
// service is configurable via a Layer parameter because some tests stub it
// while others need the real implementation.

